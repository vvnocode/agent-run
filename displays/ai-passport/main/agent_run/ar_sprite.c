static const ar_sprite_frame_t FRAMES[AR_POSE_COUNT][AR_SPRITE_FRAMES] = {
    [AR_POSE_SLEEP] = { FRAME(SLEEP_0, 0), FRAME(SLEEP_1, 0) },
    [AR_POSE_WALK] = { FRAME(WALK_0, 0), FRAME(WALK_1, 0) },
    [AR_POSE_TROT] = { FRAME(TROT_0, 0), FRAME(TROT_1, 0) },
    [AR_POSE_RUN] = { FRAME(RUN_0, 0), FRAME(RUN_1, -1) },
    [AR_POSE_DASH] = { FRAME(DASH_0, 0), FRAME(DASH_1, -1) },
    [AR_POSE_WAVE] = { FRAME(WAVE_0, 0), FRAME(WAVE_1, 0) },
};

const ar_sprite_frame_t *ar_sprite_frame(ar_pose_t pose, int frame) {
    if ((int)pose < 0 || pose >= AR_POSE_COUNT) return NULL;
    if (frame < 0) frame = -frame;
    return &FRAMES[pose][frame % AR_SPRITE_FRAMES];
}
